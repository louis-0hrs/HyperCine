"""Real CLI/P6 interoperability on two tiny self-generated synthetic frames.

The corpus is generated by this same encoder, exclusively for this test. Its
SDK-named fields are schema adapters, NOT original-SDK provenance or parity
evidence. Actual CFHD parsing, profile state, output transactions and repeated
CTest run selection are exercised together without mocks or private fixtures.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile

import reference_sample


class IntegrationFailure(Exception):
    pass


def require(condition, message):
    if not condition:
        raise IntegrationFailure(message)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def snapshot(root):
    return {p.relative_to(root).as_posix(): digest(p.read_bytes())
            for p in root.rglob("*") if p.is_file()}


def run(label, command, success=True):
    try:
        result = subprocess.run(command, stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, timeout=45)
    except subprocess.TimeoutExpired:
        raise IntegrationFailure(label + " timed out") from None
    if success:
        require(result.returncode == 0, "%s failed (exit %d)" % (label, result.returncode))
    else:
        require(result.returncode != 0, label + " accepted an occupied run")
    return result


def verify_report(path):
    report = json.loads(path.read_text(encoding="utf-8"))
    require(report.get("status") == "PASS" and report.get("failures") == [],
            "real parity integration did not publish a complete PASS report")
    profiles = report.get("profiles", {})
    require(set(profiles) == {"filmscan3"}, "unexpected measured profile set")
    measured = profiles["filmscan3"]
    require(measured.get("requested_frames") == 2 and measured.get("traced_frames") == 2,
            "real parity integration did not compare both frames")
    require(all(measured.get(key) is True for key in (
        "all_length_equal", "all_normalized_equal", "all_tables_match")),
        "self-generated synthetic replay diverged")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--encoder", required=True, type=Path)
    args = parser.parse_args()
    encoder = args.encoder.resolve(strict=True)
    source = Path(__file__).resolve().parents[1]
    parity = source / "tools" / "p6_writer_parity.py"
    runner = source / "tests" / "run_p6_writer_parity.py"
    with tempfile.TemporaryDirectory(prefix="p6-real-output-") as temporary:
        root = Path(temporary).resolve()
        seed_inputs = root / "seed-inputs"
        seed_inputs.mkdir()
        inputs = []
        for frame_index in range(2):
            data = bytearray()
            for y in range(24):
                for x in range(128):
                    data.extend(((3*x + 5*y + 17*frame_index) & 255,
                                 (7*x + 2*y + 23*frame_index) & 255,
                                 (x + 11*y + 31*frame_index) & 255, 255))
            path = seed_inputs / ("seed_%04d.bgra" % frame_index)
            path.write_bytes(data)
            inputs.append(path)
        seed_hashes = snapshot(seed_inputs)
        reference = root / "synthetic-reference"
        run("reference CLI encode", [str(encoder), "--geometry", "128x24",
            "--quality", "filmscan3", str(reference), *map(str, inputs)])
        trace = json.loads((reference / "trace.json").read_text(encoding="utf-8"))
        require([f["frame_index"] for f in trace["frames"]] == [0, 1],
                "reference CLI trace frame order changed")
        corpus = root / "synthetic-corpus"
        base = corpus / "filmscan3" / "tiny-128x24"
        frames = []
        for index, (input_path, state) in enumerate(zip(inputs, trace["frames"])):
            folder = base / "frames" / "synthetic-sequence-128x24" / ("frame_%04d" % index)
            folder.mkdir(parents=True)
            bgra = input_path.read_bytes()
            packet = (reference / ("frame_%04d.cfhd" % index)).read_bytes()
            parsed = reference_sample.parse_sample(packet)
            require(len(parsed["bands"]) == 30, "reference packet did not parse into 30 CFHD bands")
            (folder / "input.bgra").write_bytes(bgra)
            (folder / "sdk.cfhd").write_bytes(packet)
            frames.append(dict(frame_index=index, width=128, height=24,
                input_byte_length=len(bgra), input_sha256=digest(bgra),
                sdk_byte_length=len(packet), sdk_sha256=digest(packet),
                metadata_mask_ranges=parsed["metadata_mask_ranges"],
                pattern="SYNTHETIC self-generated integration frame",
                quant=state["quant"], scale=state["scale"]))
        manifest = {
            "provenance": "SYNTHETIC self-generated by the encoder under test",
            "scope": "CLI/P6 output interoperability only; NOT original-SDK parity",
            "frames": frames,
        }
        (base / "manifest.json").write_text(json.dumps(manifest), encoding="utf-8")
        records = ["%s\t%d\t%s" % (p.relative_to(corpus).as_posix(), p.stat().st_size,
                                     digest(p.read_bytes()))
                   for p in sorted(corpus.rglob("*")) if p.is_file()]
        (corpus / "TRANSFER_SHA256.tsv").write_text("\n".join(records) + "\n", encoding="ascii")
        corpus_hashes = snapshot(corpus)
        reference_hashes = snapshot(reference)
        work = root / "first-run"
        common = ["--corpus", str(corpus), "--encoder", str(encoder),
                  "--geometry", "tiny-128x24", "--profiles", "filmscan3", "--max-frames", "2"]
        direct = [sys.executable, "-B", str(parity), *common,
                  "--work", str(work), "--report", str(work / "report.json")]
        run("real P6 replay", direct)
        verify_report(work / "report.json")
        first_hashes = snapshot(work)
        refusal = run("occupied P6 replay", direct, success=False)
        require(b"already exists" in refusal.stderr,
                "occupied P6 replay failed for an unrelated reason")
        require(snapshot(work) == first_hashes, "occupied replay changed retained run bytes")

        wrapper_root = root / "ctest-runs"
        wrapper_root.mkdir()
        wrapped = [sys.executable, "-B", str(runner), *common,
                   "--work-root", str(wrapper_root)]
        run("first CTest adapter replay", wrapped)
        first_runs = sorted(wrapper_root.glob("p6-parity-*"))
        require(len(first_runs) == 1 and first_runs[0].is_dir(), "adapter did not create one fresh run")
        verify_report(first_runs[0] / "report.json")
        retained = snapshot(first_runs[0])
        run("second CTest adapter replay", wrapped)
        all_runs = sorted(wrapper_root.glob("p6-parity-*"))
        require(len(all_runs) == 2 and all(p.is_dir() for p in all_runs),
                "repeated adapter did not select a separate new run")
        for path in all_runs:
            verify_report(path / "report.json")
        require(snapshot(first_runs[0]) == retained, "second adapter run changed the first run")
        require(snapshot(work) == first_hashes, "adapter changed the direct run")
        require(snapshot(corpus) == corpus_hashes, "real replay changed retained corpus bytes")
        require(snapshot(reference) == reference_hashes, "real replay changed reference packets")
        require(snapshot(seed_inputs) == seed_hashes, "real replay changed retained seed inputs")
    print("p6_output_integration: PASS (real 2-frame CLI/P6 replay, occupied-run preservation, "
          "two separate adapter runs; SYNTHETIC interoperability only, NOT original-SDK parity)")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except IntegrationFailure as error:
        raise SystemExit("p6_output_integration: FAIL: " + str(error)) from None
    except (OSError, ValueError, KeyError, TypeError):
        raise SystemExit("p6_output_integration: FAIL: invalid filesystem or fixture contract") from None
